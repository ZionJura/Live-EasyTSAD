"""Drive the trimmed DeepSeek Harness (`dsh --profile headless`) for one agent run.

The harness does not re-implement the agent loop. It renders a per-task patch
(LLM route, system prompt, TSAD MCP tool server, session root inside the task
dir), launches `dsh` with `--json`, mirrors the NDJSON event stream into
`<task>/dsh/runs/<n>-<phase>.ndjson`, and enforces the budget from outside
(step count and wall clock) by terminating the process.
"""
from __future__ import annotations

import json
import os
import signal
import subprocess
import threading
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from .config import HARNESS_DIR, PROMPTS_DIR, ROOT, load
from .task import Task, now


@dataclass
class RunResult:
    session_id: str | None
    reason: str                    # completed | error | aborted | max-tokens | budget-steps | budget-time | crash
    final_text: str = ""
    steps: int = 0
    tool_calls: int = 0
    usage: dict = field(default_factory=dict)
    error: str = ""
    events_path: Path | None = None
    reached_model: bool = False    # True once any step_start was seen
    saw_turn_end: bool = False

    @property
    def ok(self) -> bool:
        return self.reason == "completed"


def render_system_prompt(task: Task) -> str:
    text = (PROMPTS_DIR / "system.md").read_text()
    return text.format(root=ROOT, task_dir=task.dir, method=task.method,
                       method_dir=task.method_dir.relative_to(ROOT))


def render_patch(task: Task) -> Path:
    """Write <task>/dsh/runtime.patch.yml (applied after trim.patch.yml)."""
    cfg = load()
    llm = cfg["llm"]
    model = {"id": llm["model"], "name": llm["model"], "input": ["text"],
             "contextWindow": int(llm["context_window"]), "maxTokens": int(llm["max_output_tokens"])}
    if llm.get("reasoning_effort"):
        model["reasoningEfforts"] = {e: e for e in ("low", "medium", "high")}
    default_model = {"provider": llm["provider"], "model": llm["model"]}
    if llm.get("reasoning_effort"):
        default_model["reasoningEffort"] = llm["reasoning_effort"]
    tool_env = {
        "PYTHONPATH": str(HARNESS_DIR),
        "TSAD_TASK_DIR": str(task.dir),
        "TSAD_ROOT": str(ROOT),
        "TSAD_HARNESS_CONFIG": str(Path(os.environ.get("TSAD_HARNESS_CONFIG", HARNESS_DIR / "config.toml"))),
        # mcp-client scrubs the ambient env; pass what the tools need explicitly
        "PATH": os.environ.get("PATH", ""),
        "HOME": os.environ.get("HOME", ""),
    }
    for var in ("http_proxy", "https_proxy", "HTTP_PROXY", "HTTPS_PROXY"):
        if os.environ.get(var):
            tool_env[var] = os.environ[var]
    tool_env.update({k: v for k, v in cfg.network_env().items() if k in ("NO_PROXY", "no_proxy")})
    patch = [
        {"id": "llm-pi-ai", "config": {"providers": {llm["provider"]: {
            "displayName": llm.get("display_name", llm["provider"]),
            "apiKeyEnv": cfg.dsh_key_env,
            "api": {"responses": "openai-responses", "chat": "openai-completions"}[llm["wire_api"]],
            "baseURL": llm["base_url"],
            "models": [model],
            # Proxies surface dropped HTTP/2 streams as PI_AI_ERROR, which DSH does not retry by default.
            "retryPolicy": {"mode": "normal", "maxRetries": int(cfg["llm"].get("max_retries", 6)),
                            "retryableCodes": ["EMPTY_RESPONSE", "RATE_LIMIT", "SERVER", "TIMEOUT",
                                               "TRANSPORT", "PI_AI_ERROR"]},
        }}}},
        {"id": "agent-default-model", "config": default_model},
        {"id": "system-prompt", "config": {"personaPrefix": render_system_prompt(task)}},
        {"id": "session-persistence-jsonl",
         "config": {"root": str(task.dir / "dsh" / "sessions"), "compression": "none"}},
        {"insert": [{"id": "tsad-tools", "name": "@deepseek-ai/dsh-mcp-client", "config": {
            "serverName": "tsad", "transport": "stdio",
            "command": str(cfg.python_bin), "args": ["-m", "tsad_harness.tools"],
            "env": tool_env, "cwd": str(ROOT),
            "startupTimeoutMs": int(cfg["dsh"].get("mcp_startup_timeout_ms", 300000)),
            "toolCallTimeoutMs": int(cfg["dsh"]["mcp_tool_timeout_ms"]),
            "failOnStartupError": True,
        }}]},
    ]
    out = task.dir / "dsh" / "runtime.patch.yml"
    out.write_text("# generated by tsad_harness.agent.render_patch; do not edit\n"
                   + yaml.safe_dump(patch, sort_keys=False, allow_unicode=True))
    return out


def run_agent(task: Task, prompt: str, *, label: str) -> RunResult:
    """One DSH headless run (one user turn, many steps) in the task's session."""
    cfg = load()
    budget = cfg["budget"]
    patch = render_patch(task)
    n = task.bump("agent_runs")
    runs_dir = task.dir / "dsh" / "runs"
    runs_dir.mkdir(parents=True, exist_ok=True)
    events_path = runs_dir / f"{n:03d}-{label}.ndjson"
    (runs_dir / f"{n:03d}-{label}.prompt.md").write_text(prompt)

    cmd = [str(cfg.dsh_bin), "--profile", cfg["dsh"]["profile"],
           "--patch", str(cfg.path("dsh", "trim_patch")), "--patch", str(patch), "--json"]
    if task.state.get("session_id"):
        cmd += ["--session-id", task.state["session_id"]]
    cmd += ["-"]
    cfg.dsh_home.mkdir(parents=True, exist_ok=True)
    _prewarm_tools(cfg)
    res = RunResult(session_id=task.state.get("session_id"), reason="crash", events_path=events_path)
    stderr_path = events_path.with_suffix(".stderr")
    timed_out = threading.Event()
    with open(events_path, "w") as ev, open(stderr_path, "w") as err:
        proc = subprocess.Popen(cmd, cwd=ROOT, env=cfg.agent_env(), stdin=subprocess.PIPE,
                                stdout=subprocess.PIPE, stderr=err, text=True,
                                start_new_session=True)
        task.log("agent/start", run=n, label=label, events=str(events_path.relative_to(task.dir)),
                 session_id=task.state.get("session_id"), pid=proc.pid)
        # wall-clock budget enforced even while dsh is silent (long model/tool call, hang)
        watchdog = threading.Timer(60 * float(budget["max_wall_minutes_per_run"]),
                                   lambda: (timed_out.set(), _terminate(proc)))
        watchdog.daemon = True
        watchdog.start()
        stop = None                # reason set by the harness when it kills dsh itself
        try:
            proc.stdin.write(prompt)
            proc.stdin.close()
            for line in proc.stdout:
                ev.write(line)
                ev.flush()
                _consume(res, line)
                if '"turn_start"' in line and _tools_failed(stderr_path):
                    stop, res.error = "tools-unavailable", stderr_path.read_text()[-3000:]
                elif res.steps > int(budget["max_steps_per_run"]):
                    stop = "budget-steps"
                if stop:
                    _terminate(proc)
                    break
        except KeyboardInterrupt:
            stop = "aborted"
            _terminate(proc)
        except (BrokenPipeError, OSError):
            pass                   # dsh died early (or was killed by the watchdog); handled below
        finally:
            watchdog.cancel()
        proc.wait()
    if timed_out.is_set():
        stop = "budget-time"
    if stop:
        res.reason = stop
    elif not res.saw_turn_end:
        res.reason = "crash"
    elif res.reason == "completed" and proc.returncode != 0:
        res.reason = "crash"       # turn finished but dsh failed afterwards (e.g. session flush)
    if res.reason != "completed" and not res.error:
        res.error = f"dsh exit code {proc.returncode}\n" + stderr_path.read_text()[-4000:]
    elif res.reason != "completed" and proc.returncode != 0:
        res.error = f"dsh exit code {proc.returncode}: {res.error}"
    task.reload()
    if res.session_id and task.state.get("session_id") != res.session_id:
        task.state["session_id"] = res.session_id
        task.save()
    task.log("agent/end", run=n, label=label, reason=res.reason, steps=res.steps,
             tool_calls=res.tool_calls, usage=res.usage, error=res.error[-1500:],
             final=res.final_text[-3000:])
    return res


def _prewarm_tools(cfg) -> None:
    """Import the MCP tool server once so DSH's stdio handshake does not time out.

    On a cold network filesystem the first `import mcp` can take ~50 s, longer than
    the MCP client's initialize timeout; a warm import takes a few seconds.
    """
    subprocess.run([str(cfg.python_bin), "-c", "import tsad_harness.tools"], cwd=ROOT,
                   env={**os.environ, "PYTHONPATH": str(HARNESS_DIR)}, capture_output=True, timeout=600)


def _tools_failed(stderr_path: Path) -> bool:
    """True when DSH reports that the TSAD MCP entry did not activate."""
    text = stderr_path.read_text() if stderr_path.exists() else ""
    return "tsad-tools" in text and ("did not activate" in text or "mcp-client(tsad)" in text)


def _consume(res: RunResult, line: str) -> None:
    try:
        e = json.loads(line)
    except json.JSONDecodeError:
        return
    t = e.get("type")
    if t == "session":
        res.session_id = e.get("sessionId")
    elif t == "status" and e.get("phase") == "step_start":
        res.steps += 1
        res.reached_model = True
    elif t == "status" and e.get("phase") == "step_end" and e.get("usage"):
        for k, v in e["usage"].items():
            if isinstance(v, (int, float)):
                res.usage[k] = res.usage.get(k, 0) + v
    elif t == "status" and e.get("phase") == "turn_end":
        r = e.get("reason") or {}
        res.saw_turn_end = True
        res.reason = r.get("kind", "error")
        if r.get("error"):
            res.error = json.dumps(r["error"], ensure_ascii=False)[:4000]
    elif t == "tool_call":
        res.tool_calls += 1
    elif t == "final":
        res.final_text = e.get("text", "")
    elif t == "error":
        res.error = e.get("message", "")


def _terminate(proc: subprocess.Popen) -> None:
    try:
        os.killpg(proc.pid, signal.SIGTERM)
        proc.wait(timeout=20)
    except (ProcessLookupError, subprocess.TimeoutExpired):
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass


__all__ = ["RunResult", "run_agent", "render_patch", "now"]
