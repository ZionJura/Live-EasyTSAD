import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const require = createRequire(new URL('../../leaderboard/package.json', import.meta.url));
const { chromium } = require('@playwright/test');
const base = process.env.DIRECTORY_URL || 'http://127.0.0.1:5174/';
const artifacts = fileURLToPath(new URL('../artifacts/', import.meta.url));
mkdirSync(artifacts, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base, { waitUntil: 'networkidle' });
  const catalog = await page.evaluate(async () => (await fetch('./projects.json')).json());
  const published = catalog.projects.filter(p => p.visibility === 'published');
  assert.equal(await page.locator('.project-card').count(), published.length);
  const displayed = await page.locator('.project-title').allTextContents();
  assert.deepEqual(displayed, [...published].sort((a,b) => (b.modifiedAt || '').localeCompare(a.modifiedAt || '') || a.title.localeCompare(b.title)).map(p => p.title));
  for (const link of await page.locator('.open-project:visible').evaluateAll(items => items.map(a => a.href))) assert.match(link, /^https?:\/\//);
  await page.screenshot({ path: artifacts + '/directory-desktop.png', fullPage: true });
  await page.getByRole('searchbox').fill(published[0].title);
  assert.equal(await page.locator('.project-card').count(), 1);
  await page.getByRole('searchbox').fill('nonexistent-project-xyz');
  assert.equal(await page.locator('#empty').isVisible(), true);
  await page.getByRole('button', { name: '清除筛选' }).click();
  assert.equal(await page.locator('.project-card').count(), published.length);
  await page.getByRole('button', { name: '内部服务', exact: true }).click();
  assert.equal(await page.locator('.project-card').count(), catalog.summary.internal);
  assert.equal(await page.locator('.open-project:visible').count(), 0);
  await page.getByRole('button', { name: '全部项目', exact: true }).click();
  assert.equal(await page.locator('.project-card').count(), catalog.summary.projects);
  await page.getByRole('combobox', { name: '排序方式' }).selectOption('name');
  assert.deepEqual(await page.locator('.project-title').allTextContents(), [...catalog.projects].sort((a,b)=>a.title.localeCompare(b.title, 'zh-CN')).map(p=>p.title));
  await page.getByRole('combobox').selectOption('modified');
  await page.getByRole('button', { name: '已挂载', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
  await page.screenshot({ path: artifacts + '/directory-mobile.png', fullPage: true });
  await page.route('**/projects.json', route => route.fulfill({ status: 503, body: '' }));
  await page.getByRole('button', { name: /刷新清单/ }).click();
  await page.getByText('暂时无法更新清单，正在显示上次成功获取的结果。').waitFor();
  assert.equal(await page.locator('.project-card').count(), published.length);
  await page.unroute('**/projects.json');
  const malicious = { ...catalog, projects: [{ ...published[0], title: '<img src=x onerror="window.injected=1">', url: 'javascript:window.injected=2' }] };
  await page.route('**/projects.json', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify(malicious) }));
  await page.getByRole('button', { name: /刷新清单/ }).click();
  await page.getByRole('heading', { name: malicious.projects[0].title, exact: true }).waitFor();
  assert.equal(await page.locator('.project-title img').count(), 0);
  assert.equal(await page.locator('.open-project:visible').count(), 0);
  assert.equal(await page.evaluate(() => window.injected), undefined);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, summary: catalog.summary, checked: ['sorting', 'search', 'filters', 'responsive layout', 'refresh failure', 'untrusted metadata and URLs'], runtimeErrors: errors }));
} finally { await browser.close(); }
